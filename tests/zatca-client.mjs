import assert from 'node:assert/strict';
import {ZatcaClient,GATEWAYS,summarizeResponse} from '../zatca/api-client.mjs';
const xml='<?xml version="1.0"?><Invoice xmlns="urn:oasis:names:specification:ubl:schema:xsd:Invoice-2"><cbc:ID>TEST</cbc:ID></Invoice>';
const payload={invoiceHash:Buffer.alloc(32,9).toString('base64'),uuid:'4ed65b9f-29e8-4765-887a-3f2f42e4966b',invoice:Buffer.from(xml).toString('base64')};
let calls=[];
const fake=async(url,init)=>{calls.push({url,init});return {status:200,ok:true,text:async()=>JSON.stringify({clearanceStatus:'CLEARED',reportingStatus:'REPORTED'})};};
assert.throws(()=>new ZatcaClient({environment:'production',token:'t',secret:'s'}),/confirmation/);
const c=new ZatcaClient({token:'test-token',secret:'test-secret',fetchImpl:fake});
const res=await c.clearance(payload);
assert.equal(res.data.clearanceStatus,'CLEARED');
assert.equal(calls[0].url,GATEWAYS.sandbox+'/invoices/clearance/single');
assert.equal(calls[0].init.headers['Clearance-Status'],'1');
assert.ok(calls[0].init.headers.authorization.startsWith('Basic '));
assert.equal(summarizeResponse('clearance',res).accepted,true);
await c.reporting(payload);
assert.equal(calls[1].init.headers['Clearance-Status'],'0');
await assert.rejects(()=>c.clearance({...payload,invoiceHash:'bad'}),/base64|32/);
await assert.rejects(()=>c.clearance({...payload,invoice:'%%%'}),/base64/);
await c.requestComplianceCsid({csrBase64:Buffer.from('csr').toString('base64'),otp:'123456'});
assert.equal(calls[2].init.headers.OTP,'123456');
assert.ok(!calls[2].init.headers.authorization);
console.log('ZATCA gateway tests passed (mock transport; not ZATCA validation).');
